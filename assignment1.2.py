class QLearningAgent:
    """Tabular Q-Learning Agent."""

    def __init__(self, state_bins=10, n_actions=3, alpha=0.1, gamma=0.95, epsilon=0.1):
        self.n_actions = n_actions
        self.alpha = alpha
        self.gamma = gamma
        self.epsilon = epsilon

        self.state_bins = state_bins
        self.n_states_per_dim = state_bins

        self.q_table = defaultdict(lambda: np.zeros(n_actions))

        self.rewards_history = []
        self.sla_violations_history = []

    def _discretize_state(self, state):
        """Convert continuous state to discrete state index."""
        state_key = []
        for i, val in enumerate(state):
            val_clipped = max(0, min(1, val))
            bin_idx = int(val_clipped * self.n_states_per_dim)
            bin_idx = min(bin_idx, self.n_states_per_dim - 1)
            state_key.append(bin_idx)
        return tuple(state_key)

    def select_action(self, state):
        """Epsilon-greedy action selection."""
        state_key = self._discretize_state(state)

        if np.random.random() < self.epsilon:
            return np.random.randint(self.n_actions)
        else:
            return np.argmax(self.q_table[state_key])

    def update(self, state, action, reward, next_state, done):
        """Update Q-table using Q-Learning update rule."""
        state_key = self._discretize_state(state)
        next_state_key = self._discretize_state(next_state)

        best_next_action = np.max(self.q_table[next_state_key])
        td_target = reward + self.gamma * best_next_action * (not done)
        td_error = td_target - self.q_table[state_key][action]

        self.q_table[state_key][action] += self.alpha * td_error

    def train(self, env, n_episodes=500, verbose=True):
        """Train Q-Learning agent."""
        rewards = []
        sla_violations = []

        for episode in range(n_episodes):
            state = env.reset()
            total_reward = 0
            episode_violations = 0

            for step in range(100):
                action = self.select_action(state)
                next_state, reward, done, info = env.step(action)

                if info['sla_violated']:
                    episode_violations += 1

                self.update(state, action, reward, next_state, done)
                state = next_state
                total_reward += reward

                if done:
                    break

            rewards.append(total_reward)
            sla_violations.append(episode_violations)

            if verbose and (episode + 1) % 50 == 0:
                avg_reward = np.mean(rewards[-50:])
                avg_violations = np.mean(sla_violations[-50:])
                print(f"Episode {episode+1}: Avg Reward = {avg_reward:.2f}, Avg SLA Violations = {avg_violations:.1f}")

        self.rewards_history = rewards
        self.sla_violations_history = sla_violations
        return rewards, sla_violations

    def evaluate(self, env, n_episodes=100, render=False):
        """Evaluate trained Q-Learning agent."""
        total_rewards = []
        total_violations = []

        for episode in range(n_episodes):
            state = env.reset()
            episode_reward = 0
            episode_violations = 0

            for step in range(100):
                state_key = self._discretize_state(state)
                action = np.argmax(self.q_table[state_key])

                next_state, reward, done, info = env.step(action)
                episode_reward += reward
                if info['sla_violated']:
                    episode_violations += 1

                if render:
                    env.render()

                state = next_state
                if done:
                    break

            total_rewards.append(episode_reward)
            total_violations.append(episode_violations)

        return {
            'mean_reward': np.mean(total_rewards),
            'std_reward': np.std(total_rewards),
            'mean_sla_violations': np.mean(total_violations),
            'sla_violation_rate': np.mean(total_violations) / 100,
            'total_violations': np.sum(total_violations)
        }


