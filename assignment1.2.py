class CloudResourceEnvironment:
    """
    Cloud Resource Scheduling Environment modeled as MDP.

    State Space:
        - CPU usage (0-100)
        - Memory usage (0-100)
        - Request rate (0-1000)
        - Current number of instances (1-10)
        - Time of day (0-23)

    Action Space:
        - 0: Decrease instances (scale down)
        - 1: Keep instances (maintain)
        - 2: Increase instances (scale up)

    Reward:
        - Positive: Low cost, meeting SLA
        - Negative: High cost, SLA violations
    """

    def __init__(self, seed=42):
        np.random.seed(seed)
        self.max_instances = 10
        self.min_instances = 1
        self.reset()

        # Resource parameters
        self.sla_threshold = 200  # ms latency threshold

        # Pricing
        self.cost_per_instance = 0.10  # $ per instance per time step

    def reset(self):
        """Reset environment to initial state."""
        # Current state
        self.cpu_usage = np.random.uniform(20, 60)
        self.memory_usage = np.random.uniform(30, 70)
        self.request_rate = np.random.uniform(100, 500)
        self.num_instances = np.random.randint(3, 7)
        self.hour = np.random.randint(0, 24)
        self.day_of_week = np.random.randint(0, 7)

        # Reward tracking
        self.total_cost = 0
        self.sla_violations = 0
        self.total_requests = 0
        self.steps = 0

        # Return initial observation
        return self._get_state()

    def _get_state(self):
        """Return current state as array."""
        return np.array([
            self.cpu_usage / 100.0,
            self.memory_usage / 100.0,
            self.request_rate / 1000.0,
            self.num_instances / float(self.max_instances),
            self.hour / 24.0,
            self.day_of_week / 7.0
        ])

    def _calculate_latency(self):
        """Calculate latency based on current load."""
        base_latency = 20
        load_per_instance = self.request_rate / max(self.num_instances, 1)
        latency = base_latency + (load_per_instance / 100) * 50
        return latency

    def step(self, action):
        """Execute action and return next state, reward, done."""
        # ── Apply action ──
        if action == 0:  # Scale down
            self.num_instances = max(self.min_instances, self.num_instances - 1)
        elif action == 1:  # Maintain
            pass
        elif action == 2:  # Scale up
            self.num_instances = min(self.max_instances, self.num_instances + 1)

        # ── Simulate environment dynamics ──
        self.request_rate = max(50, self.request_rate + np.random.uniform(-50, 50))
        self.cpu_usage = max(5, min(95, self.cpu_usage + np.random.uniform(-5, 5)))
        self.memory_usage = max(10, min(90, self.memory_usage + np.random.uniform(-3, 3)))
        self.hour = (self.hour + 1) % 24

        # ── Calculate latency ──
        latency = self._calculate_latency()
        self.total_requests += 1

        # ── Calculate reward ──
        cost = self.num_instances * self.cost_per_instance
        self.total_cost += cost

        sla_violated = latency > self.sla_threshold
        if sla_violated:
            self.sla_violations += 1
            sla_penalty = 5.0
        else:
            sla_penalty = 0.0

        reward = -cost - (sla_penalty * 2)

        # Bonus for efficient resource usage
        if not sla_violated and self.num_instances <= 5:
            reward += 0.5

        # ── Check if episode is done ──
        self.steps += 1
        done = self.steps >= 100

        # ── Return ──
        return self._get_state(), reward, done, {
            'latency': latency,
            'cost': cost,
            'sla_violated': sla_violated,
            'num_instances': self.num_instances,
            'steps': self.steps
        }

    def render(self):
        """Print current state."""
        print(f"Step: {self.steps}")
        print(f"  CPU: {self.cpu_usage:.1f}%")
        print(f"  Memory: {self.memory_usage:.1f}%")
        print(f"  Requests: {self.request_rate:.1f}")
        print(f"  Instances: {self.num_instances}")
        print(f"  Cost: {self.total_cost:.2f}")
        print(f"  SLA Violations: {self.sla_violations}")


