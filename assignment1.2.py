if TORCH_AVAILABLE:
    class DQNetwork(nn.Module):
        """Deep Q-Network for cloud resource scheduling."""

        def __init__(self, state_size=6, hidden_size=128, action_size=3):
            super(DQNetwork, self).__init__()

            self.network = nn.Sequential(
                nn.Linear(state_size, hidden_size),
                nn.ReLU(),
                nn.Linear(hidden_size, hidden_size),
                nn.ReLU(),
                nn.Linear(hidden_size, hidden_size // 2),
                nn.ReLU(),
                nn.Linear(hidden_size // 2, action_size)
            )

        def forward(self, x):
            return self.network(x)

    class DQNAgent:
        """Deep Q-Network Agent."""

        def __init__(self, state_size=6, action_size=3,
                     learning_rate=0.001, gamma=0.95,
                     epsilon=1.0, epsilon_min=0.01,
                     epsilon_decay=0.995, buffer_size=10000,
                     batch_size=32, target_update=100):

            self.state_size = state_size
            self.action_size = action_size
            self.gamma = gamma
            self.epsilon = epsilon
            self.epsilon_min = epsilon_min
            self.epsilon_decay = epsilon_decay
            self.batch_size = batch_size
            self.target_update = target_update

            self.device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
            self.q_network = DQNetwork(state_size, 128, action_size).to(self.device)
            self.target_network = DQNetwork(state_size, 128, action_size).to(self.device)
            self.target_network.load_state_dict(self.q_network.state_dict())

            self.optimizer = optim.Adam(self.q_network.parameters(), lr=learning_rate)
            self.memory = deque(maxlen=buffer_size)

            self.rewards_history = []
            self.sla_violations_history = []
            self.loss_history = []

            self.step_count = 0

        def select_action(self, state):
            """Epsilon-greedy action selection."""
            if np.random.random() < self.epsilon:
                return np.random.randint(self.action_size)

            state_tensor = torch.FloatTensor(state).unsqueeze(0).to(self.device)
            with torch.no_grad():
                q_values = self.q_network(state_tensor)
            return np.argmax(q_values.cpu().numpy())

        def remember(self, state, action, reward, next_state, done):
            """Store experience in replay buffer."""
            self.memory.append((state, action, reward, next_state, done))

        def replay(self):
            """Train network on batch from replay buffer."""
            if len(self.memory) < self.batch_size:
                return

            batch = random.sample(self.memory, self.batch_size)
            states = torch.FloatTensor([e[0] for e in batch]).to(self.device)
            actions = torch.LongTensor([e[1] for e in batch]).to(self.device)
            rewards = torch.FloatTensor([e[2] for e in batch]).to(self.device)
            next_states = torch.FloatTensor([e[3] for e in batch]).to(self.device)
            dones = torch.FloatTensor([e[4] for e in batch]).to(self.device)

            current_q = self.q_network(states).gather(1, actions.unsqueeze(1))
            next_q = self.target_network(next_states).max(1)[0].detach()
            target = rewards + (1 - dones) * self.gamma * next_q

            loss = nn.MSELoss()(current_q.squeeze(), target)

            self.optimizer.zero_grad()
            loss.backward()
            self.optimizer.step()

            self.loss_history.append(loss.item())

            self.epsilon = max(self.epsilon_min, self.epsilon * self.epsilon_decay)

            self.step_count += 1
            if self.step_count % self.target_update == 0:
                self.target_network.load_state_dict(self.q_network.state_dict())

        def train(self, env, n_episodes=500, verbose=True):
            """Train DQN agent."""
            rewards = []
            sla_violations = []

            for episode in range(n_episodes):
                state = env.reset()
                total_reward = 0
                episode_violations = 0

                for step in range(100):
                    action = self.select_action(state)
                    next_state, reward, done, info = env.step(action)

                    if info['sla_violated']:
                        episode_violations += 1

                    self.remember(state, action, reward, next_state, done)
                    self.replay()

                    state = next_state
                    total_reward += reward

                    if done:
                        break

                rewards.append(total_reward)
                sla_violations.append(episode_violations)

                if verbose and (episode + 1) % 50 == 0:
                    avg_reward = np.mean(rewards[-50:])
                    avg_violations = np.mean(sla_violations[-50:])
                    print(f"Episode {episode+1}: Avg Reward = {avg_reward:.2f}, "
                          f"Avg SLA Violations = {avg_violations:.1f}, "
                          f"Epsilon = {self.epsilon:.3f}")

            self.rewards_history = rewards
            self.sla_violations_history = sla_violations
            return rewards, sla_violations

        def evaluate(self, env, n_episodes=100, render=False):
            """Evaluate trained DQN agent."""
            total_rewards = []
            total_violations = []

            self.q_network.eval()

            for episode in range(n_episodes):
                state = env.reset()
                episode_reward = 0
                episode_violations = 0

                for step in range(100):
                    state_tensor = torch.FloatTensor(state).unsqueeze(0).to(self.device)
                    with torch.no_grad():
                        q_values = self.q_network(state_tensor)
                    action = np.argmax(q_values.cpu().numpy())

                    next_state, reward, done, info = env.step(action)
                    episode_reward += reward
                    if info['sla_violated']:
                        episode_violations += 1

                    state = next_state
                    if done:
                        break

                total_rewards.append(episode_reward)
                total_violations.append(episode_violations)

            return {
                'mean_reward': np.mean(total_rewards),
                'std_reward': np.std(total_rewards),
                'mean_sla_violations': np.mean(total_violations),
                'sla_violation_rate': np.mean(total_violations) / 100,
                'total_violations': np.sum(total_violations)
            }


